    """Create the accounts, threads, and usage_events tables."""
    op.execute(
        """
        -- Created by the home, never by sign-up. Each account is exactly one
        -- staff member or one family member.
        CREATE TABLE accounts (
            id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email            text NOT NULL,
            password_hash    text NOT NULL,
            role             text NOT NULL CHECK (role IN ('staff', 'family')),
            staff_id         integer UNIQUE REFERENCES staff (id),
            family_member_id integer UNIQUE REFERENCES family_members (id),
            created_at       timestamptz NOT NULL DEFAULT now(),
            CHECK (
                (role = 'staff' AND staff_id IS NOT NULL AND family_member_id IS NULL)
                OR (role = 'family' AND family_member_id IS NOT NULL AND staff_id IS NULL)
            )
        );
        CREATE UNIQUE INDEX accounts_email ON accounts (lower(email));

        -- Who owns each conversation. The messages themselves are stored by
        -- LangGraph's checkpointer under the same thread id.
        CREATE TABLE threads (
            id         uuid PRIMARY KEY,
            account_id integer NOT NULL REFERENCES accounts (id),
            created_at timestamptz NOT NULL DEFAULT now()
        );
        CREATE INDEX threads_account ON threads (account_id, created_at);

        -- One row per chat request, for cost per user. Never used to block a request (ADR-0009).
        CREATE TABLE usage_events (
            id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            account_id    integer NOT NULL REFERENCES accounts (id),
            thread_id     uuid NOT NULL REFERENCES threads (id),
            created_at    timestamptz NOT NULL DEFAULT now(),
            route         text,
            input_tokens  integer NOT NULL DEFAULT 0,
            output_tokens integer NOT NULL DEFAULT 0,
            duration_ms   integer NOT NULL
        );
        CREATE INDEX usage_events_account ON usage_events (account_id, created_at);
        """
    )


